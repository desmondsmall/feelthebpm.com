#!/usr/bin/env node
// Ranking eval for song search: queries a person would type, each with the song that should come
// first, run against the real search.db through api/search.mjs. Read-only.
//
//   node pipeline/search/eval-ranking.mjs            report for the current boosts
//   node pipeline/search/eval-ranking.mjs --sweep    also compare alternative boost settings
//
// Writes .mind/search-ranking-eval.md (a snapshot, overwritten each run). Exits non-zero if any
// query's expected song isn't first, so it can gate a ranking change.
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Search, BOOST } from '../../api/search.mjs';
import { normalize } from '../../api/normalize.mjs';
import { SEARCH_DB } from './paths.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
// [query, expected artist, expected title] — matched on normalized "contains". Prefixes are what
// someone sees while still typing. An artist-only query expects any song by that artist.
const CASES = [
  ['yesterday', 'the beatles', 'yesterday'], ['hello', 'adele', 'hello'], ['let it be', 'the beatles', 'let it be'],
  ['believer', 'imagine dragons', 'believer'], ['creep', 'radiohead', 'creep'], ['wonderwall', 'oasis', 'wonderwall'],
  ['wonderw', 'oasis', 'wonderwall'], ['smells like', 'nirvana', 'smells like teen spirit'], ['smells li', 'nirvana', 'smells like teen spirit'],
  ['bohem', 'queen', 'bohemian rhapsody'], ['bohemian rhapsody', 'queen', 'bohemian rhapsody'], ['queen', 'queen', ''],
  ['metallica', 'metallica', ''], ['adele', 'adele', ''], ['beatles yesterday', 'the beatles', 'yesterday'],
  ['yesterday beatles', 'the beatles', 'yesterday'], ['blinding lights', 'the weeknd', 'blinding lights'], ['billie jean', 'michael jackson', 'billie jean'],
  ['billie j', 'michael jackson', 'billie jean'], ['beat it', 'michael jackson', 'beat it'], ['sweet child', 'guns n roses', 'sweet child'],
  ["don't stop believin", 'journey', 'dont stop believin'], ['hey jude', 'the beatles', 'hey jude'], ['shape of you', 'ed sheeran', 'shape of you'],
  ['seven nation army', 'the white stripes', 'seven nation army'], ['take on me', 'a ha', 'take on me'], ['africa', 'toto', 'africa'],
  ['hotel california', 'eagles', 'hotel california'], ['uptown funk', 'bruno mars', 'uptown funk'], ['get lucky', 'daft punk', 'get lucky'],
  ['rolling in the deep', 'adele', 'rolling in the deep'], ['thriller', 'michael jackson', 'thriller'], ['imagine', 'john lennon', 'imagine'],
  ['humble', 'kendrick lamar', 'humble'], ['toxic', 'britney spears', 'toxic'], ['mr brightside', 'the killers', 'mr brightside'],
  ['stairway', 'led zeppelin', 'stairway to heaven'], ['despacito', 'luis fonsi', 'despacito'], ['radiohead creep', 'radiohead', 'creep'],
  ['nirvana', 'nirvana', ''],
];

const search = new Search(SEARCH_DB);
const matches = (r, a, t) => normalize(r.artist).includes(a) && normalize(r.title).includes(t);

function run() {
  return CASES.map(([q, a, t]) => {
    const t0 = performance.now();
    const items = search.search({ q, limit: 10 }).items;
    const ms = performance.now() - t0;
    const pos = items.findIndex((r) => matches(r, a, t));
    return { q, a, t, pos, ms, first: items[0] ? `${items[0].artist} — ${items[0].title}` : '(none)' };
  });
}
const summary = (rows) => {
  const firsts = rows.filter((r) => r.pos === 0).length, top3 = rows.filter((r) => r.pos >= 0 && r.pos < 3).length;
  const ms = rows.map((r) => r.ms).sort((x, y) => x - y);
  return { firsts, top3, n: rows.length, median: ms[Math.floor(ms.length / 2)], max: ms[ms.length - 1] };
};

run();   // warm the page cache so timings reflect a warm server
const base = { ...BOOST };
const rows = run();
const s = summary(rows);
const L = [];
L.push(`# Search ranking eval`, '');
L.push(`Generated by \`pipeline/search/eval-ranking.mjs\` against \`search.db\` (${search.count.toLocaleString()} songs, built ${search.manifest?.built_at ?? '?'}). A snapshot: rerun rather than edit.`, '');
L.push(`Boosts: ${Object.entries(base).map(([k, v]) => `${k} ${v}`).join(', ')}.`, '');
L.push(`**${s.firsts}/${s.n} first, ${s.top3}/${s.n} in the top 3.** Query time (laptop, warm): median ${s.median.toFixed(1)} ms, max ${s.max.toFixed(1)} ms.`, '');
L.push('| query | expected | position | first result | ms |', '|---|---|---|---|---|');
for (const r of rows) L.push(`| ${r.q} | ${r.a}${r.t ? ` — ${r.t}` : ''} | ${r.pos === 0 ? '1' : r.pos > 0 ? `**${r.pos + 1}**` : '**not in top 10**'} | ${r.first.replace(/\|/g, '/')} | ${r.ms.toFixed(1)} |`);

if (process.argv.includes('--sweep')) {
  L.push('', '## Boost sweep', '', '| artistTitle | exactTitle | exactArtist | titlePrefix | first | top 3 |', '|---|---|---|---|---|---|');
  for (const at of [20, 40, 80]) for (const et of [4, 8, 12, 20, 40]) for (const ea of [3, 6, 12, 24]) {
    Object.assign(BOOST, { artistTitle: at, exactTitle: et, exactArtist: ea, titlePrefix: 1 });
    const x = summary(run());
    L.push(`| ${at} | ${et} | ${ea} | 1 | ${x.firsts} | ${x.top3} |`);
  }
  Object.assign(BOOST, base);
}

const out = join(HERE, '..', '..', '.mind', 'search-ranking-eval.md');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, L.join('\n') + '\n');
console.log(`${s.firsts}/${s.n} first, ${s.top3}/${s.n} top 3; median ${s.median.toFixed(1)} ms, max ${s.max.toFixed(1)} ms → ${out}`);
for (const r of rows.filter((r) => r.pos !== 0)) console.log(`  "${r.q}": expected at ${r.pos < 0 ? '—' : r.pos + 1}, first is ${r.first}`);
process.exitCode = s.firsts === s.n ? 0 : 1;
